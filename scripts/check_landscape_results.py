#!/usr/bin/env python3
"""Independently audit the frozen, SIMULATED landscape balanced subset.

No model calls or empirical inputs. Requires NumPy for exact bootstrap replay.
The PDF/SVG are published vector assets, not regenerated by this checker.
"""

import csv
import hashlib
import json
import math
from collections import Counter, defaultdict
from pathlib import Path
import re
import subprocess

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/simulated/landscape"
METHODS = ("Static judge", "Static tools", "Prompt optimization", "Program search", "ERA")
SEED = 20260918


def require(condition, message):
    if not condition:
        raise ValueError(message)


def close(actual, expected):
    require(math.isclose(float(actual), float(expected), rel_tol=1e-9, abs_tol=1e-9),
            f"Numerical mismatch: {actual} != {expected}")


def read(path, geometry=False):
    with path.open(newline="", encoding="utf-8") as stream:
        rows = list(csv.DictReader(stream))
    require(bool(rows), f"Empty export: {path}")
    if not geometry:
        require(all(r.get("provenance") == "SIMULATED" for r in rows),
                f"Missing synthetic provenance: {path}")
    return rows


def index(rows, fields):
    result = {tuple(r[f] for f in fields): r for r in rows}
    require(len(rows) == len(result), "Duplicate export keys")
    return result


def sample_key(domain, group):
    return hashlib.sha256(f"{SEED}|{domain}|{group}".encode()).hexdigest()


def main():
    manifest = json.loads((DATA / "manifest.json").read_text())
    require(manifest["simulation_only"] is True and manifest["empirical_evidence"] is False,
            "Simulation evidence boundary changed")
    require(manifest["selection_seed"] == SEED and manifest["bootstrap_replicates"] == 1000,
            "Balanced-subset protocol changed")
    required = {str(p.relative_to(ROOT)) for p in DATA.glob("*.csv")}
    required.update({"data/simulated/c1_groups.csv", "data/simulated/c1_cohorts.csv",
                     "figures/simulated_landscape.tex", "scripts/check_landscape_results.py"})
    required.update("figures/simulated/landscape_outcomes." + ext for ext in ("pdf", "svg", "png"))
    require(set(manifest["files"]) == required, "Incomplete frozen-asset manifest")
    for relative, digest in manifest["files"].items():
        path = (ROOT / relative).resolve()
        path.relative_to(ROOT)
        require(hashlib.sha256(path.read_bytes()).hexdigest() == digest, f"Stale asset: {relative}")

    cohorts = index(read(ROOT / "data/simulated/c1_cohorts.csv"), ("domain",))
    composition = index(read(DATA / "domain-composition.csv"), ("domain",))
    require(set(cohorts) == set(composition) and len(composition) == 22, "Task coverage changed")
    family_sizes = Counter(r["family"] for r in composition.values())
    require(sorted(family_sizes.values()) == [5, 5, 6, 6], "Family taxonomy changed")
    raw = [r for r in read(ROOT / "data/simulated/c1_groups.csv") if r["split"] == "OOD"]
    inputs = defaultdict(set)
    for r in raw:
        inputs[r["domain"]].add(r["input_group"])
    selections = read(DATA / "selected-inputs.csv")
    require(len(index(selections, ("domain", "input_group"))) == 2880, "Wrong subset size")
    selected = defaultdict(set)
    for r in selections:
        require(r["selection_hash"] == sample_key(r["domain"], r["input_group"]), "Selection hash changed")
        require(r["family"] == composition[(r["domain"],)]["family"], "Selection family mismatch")
        selected[r["domain"]].add(r["input_group"])
    for (did,), r in composition.items():
        n = 720 // family_sizes[r["family"]]
        expected = set(sorted(inputs[did], key=lambda g: sample_key(did, g))[:n])
        require(len(inputs[did]) == 160 and selected[did] == expected, "Outcome-blind selection changed")
        require(int(r["requested_input_groups"]) == n and int(r["candidate_slots"]) == 4*n,
                "Composition counts disagree")
        require(r["setting"] == cohorts[(did,)]["setting"] and r["split"] == "OOD", "Setting changed")
    kept = [r for r in raw if r["input_group"] in selected[r["domain"]]]
    groups = defaultdict(list)
    by_method = defaultdict(list)
    for r in kept:
        groups[(r["domain"], r["input_group"])].append(r)
        by_method[(r["domain"], r["method"])].append(r)
    all_methods = set(METHODS) | {"Single metric", "Metric ensemble"}
    require(all(len(g) == 7 and {r["method"] for r in g} == all_methods for g in groups.values()),
            "Selection discarded methods or incomplete responses")
    summaries = index(read(DATA / "method-summaries.csv"), ("domain", "method"))
    expected_keys = {(d, m) for d, in composition for m in METHODS}
    require(set(summaries) == expected_keys, "Method summary coverage changed")
    for (did, method), r in summaries.items():
        group = by_method[(did, method)]
        complete = [g for g in group if g["complete"] == "1"]
        require(int(r["requested_groups"]) == len(group) and int(r["complete_groups"]) == len(complete),
                "Wrong completeness denominator")
        require(r["setting"] == composition[(did,)]["setting"] and r["split"] == "OOD", "Summary setting changed")
        values = np.asarray([float(g["pairwise"]) for g in complete])
        rng = np.random.default_rng(int(sample_key(did, "bootstrap-" + method)[:16], 16))
        boot = values[rng.integers(0, len(values), (1000, len(values)))].mean(axis=1)
        lower, upper = np.quantile(boot, [.025, .975])
        for key, value in (("mean", values.mean()), ("lower", lower), ("upper", upper),
                           ("best_of_4", np.mean([float(g["best_of_4"]) for g in complete])),
                           ("cost_units", np.mean([float(g["cost_units"]) for g in group]))):
            close(r[key], value)
    bars = index(read(DATA / "displayed-bars.csv"), ("domain", "method"))
    geometry = index(read(DATA / "bar-geometry.csv", geometry=True), ("domain", "method"))
    require(set(bars) == set(geometry) == expected_keys, "Missing bars or intervals")
    for key, r in bars.items():
        geom = geometry[key]
        close(geom["full_scale_height_inches"], .55)
        close(geom["zero_inches"], .41)
        for plotted, source in (("agreement_pct", "mean"), ("lower_pct", "lower"), ("upper_pct", "upper")):
            close(r[plotted], 100*float(summaries[key][source]))
            close(geom[source+"_inches"], .41+.55*float(summaries[key][source]))
    macros = index(read(DATA / "displayed-macros.csv"), ("setting", "method"))
    require(set(macros) == {(s, m) for s in ("Reuse", "Collect") for m in METHODS}, "Missing setting means")
    for (setting, method), r in macros.items():
        source = [s for s in summaries.values() if s["setting"] == setting and s["method"] == method]
        require(len(source) == int(r["domain_count"]) == 11, "Wrong macro denominator")
        for key, field, scale in (("agreement_pct", "mean", 100), ("assigned_cost", "cost_units", 1),
                                  ("best_of_4_pct", "best_of_4", 100)):
            close(r[key], scale*np.mean([float(s[field]) for s in source]))
    for name, fields, sources, xfield, yfield, scale in (
        ("domain-points.csv", ("domain", "method"), summaries, "cost_units", "mean", 100),
        ("displayed-points.csv", ("setting", "method"), macros, "assigned_cost", "agreement_pct", 1),
    ):
        points = index(read(DATA / name), fields)
        require(set(points) == set(sources), "Scatter point coverage changed")
        for key, r in points.items():
            s = sources[key]
            close(r[xfield], s[xfield])
            close(r[yfield], s[yfield])
            close(r["x_inches"], 3.18+(float(s[xfield])-.65)/1.1*2.07)
            close(r["y_inches"], (3.79+(scale*float(s[yfield])-60)/24*1.69)*.62-.445)
    angles = defaultdict(float)
    for r in read(DATA / "sector-colors.csv"):
        angle = float(r["end_degrees"])-float(r["start_degrees"])
        close(angle, 360*int(r["requested_input_groups"])/2880)
        angles[r["family"]] += angle
    require(len(angles) == 4, "Missing ring family")
    for angle in angles.values():
        close(angle, 90)
    pdf = ROOT / "figures/simulated/landscape_outcomes.pdf"
    text = subprocess.check_output(["pdftotext", str(pdf), "-"], text=True)
    require("SIMULATED" in text and "not experimental results" in text, "Visible disclosure missing")
    require("IterEval" in text and not re.search(r"\b(?:ERA|IPM)\b", text),
            "Framework display label is missing or retired")
    expected_codes = {d.removeprefix("TD-") if hasattr(d, "removeprefix") else d[3:] for d, in composition}
    require(set(re.findall(r"\b(?:SV|IG|TG|AR)\d+\b", text)) == expected_codes, "Missing visible task codes")
    print("Balanced landscape: 2,880 synthetic inputs, 110 bars and intervals, 120 scatter points verified.")
    print("SIMULATED layout only; no effectiveness claim is validated.")


if __name__ == "__main__":
    main()
